// 乘除模：* / %
表达式指针 语法分析::解析乘除模() {
    auto 左 = 解析一元();
    while (检查(词元类型::星号) || 检查(词元类型::斜杠)
           || 检查(词元类型::百分号)) {
        auto 节点 = std::make_unique<二元运算节点>();
        节点->行号 = 当前().行号;
        节点->列号 = 当前().列号;
        节点->运算符 = 当前().类型;
        位置_++;
        节点->左 = std::move(左);
        节点->右 = 解析一元();
        左 = std::move(节点);
    }
    return 左;
}

// 一元：+ - ! ~ ^
表达式指针 语法分析::解析一元() {
    if (检查(词元类型::减号) || 检查(词元类型::加号)
        || 检查(词元类型::叹号) || 检查(词元类型::波浪号)
        || 检查(词元类型::脱字符)) {
        auto 节点 = std::make_unique<一元运算节点>();
        节点->行号 = 当前().行号;
        节点->列号 = 当前().列号;
        节点->运算符 = 当前().类型;
        位置_++;
        节点->操作数 = 解析一元();
        return 节点;
    }
    return 解析后缀();
}

// 后缀：调用 () / 索引 [] / 成员 .
表达式指针 语法分析::解析后缀() {
    auto 表达式 = 解析基础();
    while (true) {
        if (匹配(词元类型::左圆括号)) {
            auto 节点 = std::make_unique<调用节点>();
            节点->行号 = 当前().行号;
            节点->列号 = 当前().列号;
            节点->被调 = std::move(表达式);
            if (!检查(词元类型::右圆括号)) {
                do {
                    节点->实参.push_back(解析表达式());
                } while (匹配(词元类型::逗号));
            }
            期望(词元类型::右圆括号, ")");
            表达式 = std::move(节点);
        } else if (匹配(词元类型::左方括号)) {
            auto 节点 = std::make_unique<索引节点>();
            节点->行号 = 当前().行号;
            节点->列号 = 当前().列号;
            节点->对象 = std::move(表达式);
            节点->下标 = 解析表达式();
            期望(词元类型::右方括号, "]");
            表达式 = std::move(节点);
        } else if (匹配(词元类型::点号)) {
            auto 节点 = std::make_unique<成员访问节点>();
            节点->行号 = 当前().行号;
            节点->列号 = 当前().列号;
            节点->对象 = std::move(表达式);
            const auto& 成员 = 期望(词元类型::名称, "成员名");
            节点->成员 = 成员.文本;
            表达式 = std::move(节点);
        } else {
            break;
        }
    }
    return 表达式;
}

// 基础：字面量 / 名称 / 括号 / 数组字面量
表达式指针 语法分析::解析基础() {
    if (检查(词元类型::数字)) {
        auto 节点 = std::make_unique<数字字面量节点>();
        节点->行号 = 当前().行号;
        节点->列号 = 当前().列号;
        节点->文本 = 当前().文本;
        位置_++;
        return 节点;
    }
    if (检查(词元类型::文本)) {
        auto 节点 = std::make_unique<文本字面量节点>();
        节点->行号 = 当前().行号;
        节点->列号 = 当前().列号;
        节点->文本 = 当前().文本;
        位置_++;
        return 节点;
    }
    if (检查(词元类型::名称)) {
        auto 节点 = std::make_unique<名称引用节点>();
        节点->行号 = 当前().行号;
        节点->列号 = 当前().列号;
        节点->名称 = 当前().文本;
        位置_++;
        return 节点;
    }
    if (匹配(词元类型::左圆括号)) {
        auto 表达式 = 解析表达式();
        期望(词元类型::右圆括号, ")");
        return 表达式;
    }
    if (匹配(词元类型::左方括号)) {
        auto 节点 = std::make_unique<数组字面量节点>();
        节点->行号 = 当前().行号;
        节点->列号 = 当前().列号;
        if (!检查(词元类型::右方括号)) {
            do {
                节点->元素.push_back(解析表达式());
            } while (匹配(词元类型::逗号));
        }
        期望(词元类型::右方括号, "]");
        return 节点;
    }
    报错("无法解析的表达式，起始词元: " + 类型文本(当前().类型)
         + " \"" + 当前().文本 + "\"");
    return nullptr; // 不可达
}