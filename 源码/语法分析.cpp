
#include <sstream>

#include "语法分析.hpp"



语法分析::语法分析(std::vector<词元结构> 词元流)
    : 词元流_(std::move(词元流)) {}

const 词元结构& 语法分析::当前() const {
    static 词元结构 末尾哨兵{词元类型::分号, "<eof>", -1, -1};
    if (位置_ >= 词元流_.size()) return 末尾哨兵;
    return 词元流_[位置_];
}

const 词元结构& 语法分析::向前看(size_t 偏移) const {
    static 词元结构 末尾哨兵{词元类型::分号, "<eof>", -1, -1};
    if (位置_ + 偏移 >= 词元流_.size()) return 末尾哨兵;
    return 词元流_[位置_ + 偏移];
}

bool 语法分析::到末尾() const { return 位置_ >= 词元流_.size(); }

bool 语法分析::检查(词元类型 类型) const {
    return !到末尾() && 当前().类型 == 类型;
}

bool 语法分析::匹配(词元类型 类型) {
    if (检查(类型)) { 位置_++; return true; }
    return false;
}

const 词元结构& 语法分析::期望(词元类型 类型, const std::string& 说明) {
    if (!检查(类型)) 报错("期望 " + 说明 + "，实际是 " + 类型文本(当前().类型)
                          + " \"" + 当前().文本 + "\"");
    return 词元流_[位置_++];
}

void 语法分析::报错(const std::string& 信息) {
    throw 语法错误(当前().行号, 当前().列号, 信息);
}

// ==================== 顶层 ====================

程序 语法分析::解析() {
    程序 结果;
    while (!到末尾()) {
        if (检查(词元类型::函数)) {
            结果.函数列表.push_back(解析函数声明());
        } else {
            // 允许顶层脚本语句
            结果.顶层语句.push_back(解析语句());
        }
    }
    return 结果;
}

函数声明 语法分析::解析函数声明() {
    函数声明 函数;
    函数.行号 = 当前().行号;
    函数.列号 = 当前().列号;

    期望(词元类型::函数, "函数");
    const auto& 名字 = 期望(词元类型::名称, "函数名");
    函数.名称 = 名字.文本;

    期望(词元类型::左圆括号, "(");
    if (!检查(词元类型::右圆括号)) {
        do {
            参数 p;
            // 参数形式：名称 [: 类型]
            const auto& 参数名 = 期望(词元类型::名称, "参数名");
            p.名称 = 参数名.文本;
            if (匹配(词元类型::冒号)) {
                const auto& 类型名 = 期望(词元类型::名称, "类型名");
                p.类型名 = 类型名.文本;
            }
            函数.参数列表.push_back(std::move(p));
        } while (匹配(词元类型::逗号));
    }
    期望(词元类型::右圆括号, ")");

    // 返回类型：-> 类型  （用减号+大于号模拟，或直接 : 类型）
    if (匹配(词元类型::冒号)) {
        const auto& 类型名 = 期望(词元类型::名称, "返回类型");
        函数.返回类型 = 类型名.文本;
    }

    函数.函数体 = 解析代码块();
    return 函数;
}

// ==================== 语句 ====================

语句指针 语法分析::解析语句() {
    if (检查(词元类型::左花括号))  return 解析代码块();
    if (检查(词元类型::变量))       return 解析变量声明(false);
    if (检查(词元类型::常量))       return 解析变量声明(true);
    if (检查(词元类型::返回))       return 解析返回语句();
    if (检查(词元类型::如果))       return 解析如果语句();
    return 解析表达式语句();
}

语句指针 语法分析::解析代码块() {
    auto 块 = std::make_unique<代码块节点>();
    块->行号 = 当前().行号;
    块->列号 = 当前().列号;
    期望(词元类型::左花括号, "{");
    while (!检查(词元类型::右花括号) && !到末尾()) {
        块->语句列表.push_back(解析语句());
    }
    期望(词元类型::右花括号, "}");
    return 块;
}

语句指针 语法分析::解析变量声明(bool 是常量) {
    auto 节点 = std::make_unique<变量声明节点>();
    节点->是常量 = 是常量;
    节点->行号 = 当前().行号;
    节点->列号 = 当前().列号;

    位置_++; // 跳过 变量/常量
    const auto& 名字 = 期望(词元类型::名称, "变量名");
    节点->名称 = 名字.文本;

    // 可选类型标注：: 类型
    if (匹配(词元类型::冒号)) {
        const auto& 类型名 = 期望(词元类型::名称, "类型名");
        节点->类型名 = 类型名.文本;
    }

    // 可选初值：= 表达式
    if (匹配(词元类型::等号)) {
        节点->初值 = 解析表达式();
    }

    期望(词元类型::分号, ";");
    return 节点;
}

语句指针 语法分析::解析返回语句() {
    auto 节点 = std::make_unique<返回语句节点>();
    节点->行号 = 当前().行号;
    节点->列号 = 当前().列号;
    位置_++; // 跳过 返回

    if (!检查(词元类型::分号)) {
        节点->返回值 = 解析表达式();
    }
    期望(词元类型::分号, ";");
    return 节点;
}

语句指针 语法分析::解析如果语句() {
    auto 节点 = std::make_unique<如果语句节点>();
    节点->行号 = 当前().行号;
    节点->列号 = 当前().列号;
    位置_++; // 跳过 如果

    // 条件可带括号，也可不带（按表达式解析到 { 前）
    期望(词元类型::左圆括号, "(");
    节点->条件 = 解析表达式();
    期望(词元类型::右圆括号, ")");

    节点->则分支 = 解析语句();

    // 否则分支（用 "或者" 作为 else 关键词）
    if (匹配(词元类型::或者)) {
        节点->否则分支 = 解析语句();
    }
    return 节点;
}

语句指针 语法分析::解析表达式语句() {
    auto 节点 = std::make_unique<表达式语句节点>();
    节点->行号 = 当前().行号;
    节点->列号 = 当前().列号;
    节点->表达式 = 解析表达式();
    期望(词元类型::分号, ";");
    return 节点;
}

// ==================== 表达式 ====================

表达式指针 语法分析::解析表达式() {
    return 解析逻辑或();
}

// 逻辑或：或者 | |
表达式指针 语法分析::解析逻辑或() {
    auto 左 = 解析逻辑与();
    while (检查(词元类型::或者) || 检查(词元类型::竖线)) {
        auto 节点 = std::make_unique<二元运算节点>();
        节点->行号 = 当前().行号;
        节点->列号 = 当前().列号;
        节点->运算符 = 当前().类型;
        位置_++;
        节点->左 = std::move(左);
        节点->右 = 解析逻辑与();
        左 = std::move(节点);
    }
    return 左;
}

