#include "语法分析.hpp"

std::vector<语句> 语法分析::代码分析(const std::vector<词元结构>& 词法结果) {
  std::vector<语句> 分析结果;

  std::size_t 索引 = 0;
  while (索引 < 词法结果.size()) {
    const 词元类型 类型 = 词法结果[索引].类型;

    // 常量定义： 常量 类型:名称 = 量值
    if (类型 == 词元类型::常量) {
      if (索引 + 5 > 词法结果.size()) break;
      常量定义 节点;
      节点.类型 = 词法结果[索引 + 1].文本;
      节点.名称 = 词法结果[索引 + 3].文本;
      节点.量值 = 词法结果[索引 + 5].文本;
      分析结果.push_back(std::move(节点));
      索引 += 5;
      continue;
    }

    // 变量定义： 变量 类型:名称 = 量值
    if (类型 == 词元类型::变量) {
      if (索引 + 5 > 词法结果.size()) break;
      变量定义 节点;
      节点.类型 = 词法结果[索引 + 1].文本;
      节点.名称 = 词法结果[索引 + 3].文本;
      节点.量值 = 词法结果[索引 + 5].文本;
      分析结果.push_back(std::move(节点));
      索引 += 5;
      continue;
    }

    // 容量定义： 容量 类型:名称 = 量值
    if (类型 == 词元类型::容量) {
      if (索引 + 5 > 词法结果.size()) break;
      容量定义 节点;
      节点.类型 = 词法结果[索引 + 1].文本;
      节点.名称 = 词法结果[索引 + 3].文本;
      节点.量值 = 词法结果[索引 + 5].文本;
      分析结果.push_back(std::move(节点));
      索引 += 5;
      continue;
    }

    // 属性定义： 属性 类型:名称 = 量值
    if (类型 == 词元类型::属性) {
      if (索引 + 5 > 词法结果.size()) break;
      属性定义 节点;
      节点.类型 = 词法结果[索引 + 1].文本;
      节点.名称 = 词法结果[索引 + 3].文本;
      节点.量值 = 词法结果[索引 + 5].文本;
      分析结果.push_back(std::move(节点));
      索引 += 5;
      continue;
    }

    // 类型定义： 类型 类型:名称 = 量值
    if (类型 == 词元类型::类型) {
      if (索引 + 5 > 词法结果.size()) break;
      类型定义 节点;
      节点.类型 = 词法结果[索引 + 1].文本;
      节点.名称 = 词法结果[索引 + 3].文本;
      节点.量值 = 词法结果[索引 + 5].文本;
      分析结果.push_back(std::move(节点));
      索引 += 5;
      continue;
    }

    ++索引;
  }

  return 分析结果;
}