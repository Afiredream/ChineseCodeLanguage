#pragma once

#include <memory>
#include <string>
#include <vector>


struct 表达式节点;
using 表达式指针 = std::unique_ptr<表达式节点>;

enum class 语句种类 {
    定义语句,
    结构语句,
    模块语句,
    赋值语句,
    控制语句,
    访问语句
};

struct 语句节点 {
    语句种类 种类;
    int 行号;
    int 列号;
};

struct 定义语句节点 : 表达式节点 {
    std::string 文本;
    数字字面量节点() { 种类 = 表达式种类::数字字面量; }
};

struct 文本字面量节点 : 表达式节点 {
    std::string 文本;
    文本字面量节点() { 种类 = 表达式种类::文本字面量; }
};

struct 名称引用节点 : 表达式节点 {
    std::string 名称;
    名称引用节点() { 种类 = 表达式种类::名称引用; }
};

struct 一元运算节点 : 表达式节点 {
    词元类型 运算符;
    表达式指针 操作数;
    一元运算节点() { 种类 = 表达式种类::一元运算; }
};

struct 二元运算节点 : 表达式节点 {
    词元类型 运算符;
    表达式指针 左;
    表达式指针 右;
    二元运算节点() { 种类 = 表达式种类::二元运算; }
};

struct 调用节点 : 表达式节点 {
    表达式指针 被调;
    std::vector<表达式指针> 实参;
    调用节点() { 种类 = 表达式种类::调用; }
};

struct 索引节点 : 表达式节点 {
    表达式指针 对象;
    表达式指针 下标;
    索引节点() { 种类 = 表达式种类::索引; }
};

struct 成员访问节点 : 表达式节点 {
    表达式指针 对象;
    std::string 成员;
    成员访问节点() { 种类 = 表达式种类::成员访问; }
};

struct 数组字面量节点 : 表达式节点 {
    std::vector<表达式指针> 元素;
    数组字面量节点() { 种类 = 表达式种类::数组字面量; }
};

// ============ 语句节点 ============
struct 语句节点;
using 语句指针 = std::unique_ptr<语句节点>;

enum class 语句种类 {
    表达式语句,
    变量声明,
    常量声明,
    返回语句,
    如果语句,
    代码块,
};

struct 语句节点 {
    语句种类 种类;
    int 行号 = 0;
    int 列号 = 0;
    virtual ~语句节点() = default;
};

struct 表达式语句节点 : 语句节点 {
    表达式指针 表达式;
    表达式语句节点() { 种类 = 语句种类::表达式语句; }
};

struct 变量声明节点 : 语句节点 {
    bool 是常量 = false;
    std::string 名称;
    std::string 类型名;              // 可空
    表达式指针 初值;                  // 可空
    变量声明节点() { 种类 = 语句种类::变量声明; }
};

struct 返回语句节点 : 语句节点 {
    表达式指针 返回值;                // 可空
    返回语句节点() { 种类 = 语句种类::返回语句; }
};

struct 代码块节点 : 语句节点 {
    std::vector<语句指针> 语句列表;
    代码块节点() { 种类 = 语句种类::代码块; }
};

struct 如果语句节点 : 语句节点 {
    表达式指针 条件;
    语句指针 则分支;
    语句指针 否则分支;                // 可空
    如果语句节点() { 种类 = 语句种类::如果语句; }
};

// ============ 顶层：函数声明 ============
struct 参数 {
    std::string 名称;
    std::string 类型名;
};

struct 函数声明 {
    std::string 名称;
    std::vector<参数> 参数列表;
    std::string 返回类型;             // 可空
    语句指针 函数体;
    int 行号 = 0, 列号 = 0;
};

struct 程序 {
    std::vector<函数声明> 函数列表;
    std::vector<语句指针> 顶层语句;   // 支持脚本式顶层
};